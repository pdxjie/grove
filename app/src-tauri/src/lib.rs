mod commands;

pub fn run() {
    tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .invoke_handler(tauri::generate_handler![
            commands::open_repo,
            commands::repo_snapshot,
            commands::status,
            commands::log_page,
            commands::authors,
            commands::diff,
            commands::commit_detail,
            commands::stage,
            commands::stage_hunk,
            commands::stage_lines,
            commands::outgoing,
            commands::conflict_doc,
            commands::resolve_conflict,
            commands::checkout_side,
            commands::unstage,
            commands::discard,
            commands::commit,
            commands::branches,
            commands::push_branch,
            commands::track_remote,
            commands::rename_branch,
            commands::compare_branches,
            commands::pr_url,
            commands::open_url,
            commands::rebase_plan,
            commands::rebase_start,
            commands::worktree_add,
            commands::worktree_remove,
            commands::worktree_prune,
            commands::blame,
            commands::protected_rules,
            commands::set_protected_rules,
            commands::local_only,
            commands::set_local_only,
            commands::undo_last,
            commands::journal,
            commands::checkout,
            commands::create_branch,
            commands::delete_branch,
            commands::merge,
            commands::cherry_pick,
            commands::revert_commit,
            commands::sequencer_control,
            commands::undo_commit,
            commands::stash_push,
            commands::stash_files,
            commands::stash_diff,
            commands::stash_apply,
            commands::stash_drop,
            commands::fetch_all,
            commands::pull,
            commands::push,
            commands::initial_repo,
            commands::initial_ui,
            commands::cmd_log,
            commands::clear_cmd_log
        ])
        .run(tauri::generate_context!())
        .expect("error while running grove");
}
